export function getPhrasebookForCountry(countryName) {
  if (!countryName) return null;
  if (PHRASEBOOKS[countryName]) return PHRASEBOOKS[countryName];
  // Fallbacks for Latin America & others
  if (['Meksika', 'Peru', 'Arjantin', 'Şili', 'Kolombiya'].includes(countryName)) {
    return { ...PHRASEBOOKS['İspanya'], language: `${countryName} İspanyolcası` };
  }
  if (countryName === 'Brezilya') {
    return { ...PHRASEBOOKS['Portekiz'], language: 'Brezilya Portekizcesi' };
  }
  if (['ABD', 'Birleşik Krallık', 'Kanada', 'İrlanda', 'Avustralya'].includes(countryName)) {
    return {
      language: 'İngilizce',
      flag: '🇬🇧',
      phrases: [
        { tr: 'Merhaba', local: 'Hello / Hi', phonetic: 'Helo / Hay' },
        { tr: 'Teşekkürler', local: 'Thank you very much', phonetic: 'Tenk yu veri maç' },
        { tr: 'Lütfen', local: 'Please', phonetic: 'Pliyz' },
        { tr: 'Hesap lütfen', local: 'The check / bill, please', phonetic: 'Dı çek / bil, pliyz' },
        { tr: 'Ne kadar?', local: 'How much is it?', phonetic: 'Haw maç iz it?' },
      ]
    };
  }
  return null;
}
