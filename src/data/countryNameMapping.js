export function getCountryInfo(rawName) {
  if (!rawName) return null;
  const clean = rawName.trim();
  if (COUNTRY_MAPPING[clean]) return COUNTRY_MAPPING[clean];

  // Check sub-matches (e.g. "Stockholm (İsveç)" -> "İsveç")
  for (const [key, val] of Object.entries(COUNTRY_MAPPING)) {
    if (clean.includes(key)) {
      return val;
    }
  }

  return { iso: '', name: clean, flag: '🏳️', continent: 'Dünya' };
}
